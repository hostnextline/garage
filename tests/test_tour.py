def rpc(tok, name, body): return http('POST', API + '/rest/v1/rpc/' + name, body, tok)
def tip(p): return txt(p, '#tour-ov .tt-tip')
def hole(p): return p.evaluate("(() => { const h = document.querySelector('#tour-ov .tt-hole'); if (!h) return null; const r = h.getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2]; })()")
def lit(p, sel):
    """is the lit hole around this element?"""
    return p.evaluate("""(sel) => { const h = document.querySelector('#tour-ov .tt-hole'); const e = [...document.querySelectorAll(sel)].find(x => x.getBoundingClientRect().width > 0); if (!h || !e) return false;
      const a = h.getBoundingClientRect(), b = e.getBoundingClientRect(); return a.left <= b.left + 1 && a.top <= b.top + 1 && a.right >= b.right - 1 && a.bottom >= b.bottom - 1; }""", sel)
def play(p, shots=None, name=''):
    """go through the whole tour like a person: « Suivant », and touch the lit button on « À toi ! » steps"""
    seen = []
    for k in range(20):
        p.wait_for_timeout(650)
        if p.locator('#tour-ov .tt-win').count(): break
        t = tip(p); seen.append(t)
        if shots is not None and len(shots) < 4: p.screenshot(path='%s_%d.png' % (name, k)); shots.append('%s_%d.png' % (name, k))
        if 'À toi' in t:
            c = hole(p); p.mouse.click(c[0], c[1])
        else: p.click('#tour-ov [data-act="tt-next"]')
    return seen
