T0 = dt.date.fromisoformat(TODAY)
SUN = T0 - dt.timedelta(days=(T0.weekday() + 1) % 7)
D = lambda n: (SUN + dt.timedelta(days=n)).isoformat()          # 0 = dimanche … 6 = samedi of this week
def cell(p, d, t): return p.locator('#sched .sch-c[data-d="%s"][data-t="%s"]' % (d, t))
def box(p, d, t): b = cell(p, d, t).bounding_box(); return b['x'] + b['width'] / 2, b['y'] + b['height'] / 2
def drag(p, d, t1, t2, steps=4):
    # like a fast finger: few moves (the app fills the cases in between)
    cell(p, d, t1).evaluate("e => { const sc = e.closest('.sch-scroll'), h = sc.querySelector('.sch-dh'); e.scrollIntoView({block:'nearest', inline:'center'}); sc.scrollTop += e.getBoundingClientRect().top - sc.getBoundingClientRect().top - (h ? h.offsetHeight : 50) - 8; }"); p.wait_for_timeout(100)
    x1, y1 = box(p, d, t1); x2, y2 = box(p, d, t2)
    p.mouse.move(x1, y1); p.mouse.down()
    for k in range(1, steps + 1): p.mouse.move(x1 + (x2 - x1) * k / steps, y1 + (y2 - y1) * k / steps)
    p.mouse.up(); p.wait_for_timeout(150)
def summ(p, d): return txt(p, '#sched .sch-sum[data-d="%s"]' % d)
def mode(p, v): p.click('#sched [data-act="sc-mode"][data-v="%s"]' % v)
def base_tab(p):   # (with trucks, the window opens on a truck's own schedule: these checks are about the garage's base hours)
    if p.locator('#sched .sch-tabs [data-v="garage:"]').count(): p.click('#sched .sch-tabs [data-v="garage:"]'); p.wait_for_timeout(300)
