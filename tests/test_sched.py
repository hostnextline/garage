"""Fenêtre vitrée de l'horaire : semaine (ordinateur) / jour (téléphone), glisser sur les cases, appliquer seulement ce jour /
cette semaine, pendant N semaines, ou en permanence. Pour le garage et pour un mécano. Copie locale ; tout est remis à la fin."""
